                vertices.Add(vertex);
                graph.AddVertex(vertex);
            }
            
            // Connect them in a chain A->B->C->...->Z
            for (int i = 0; i < vertices.Count - 1; i++)
            {
                graph.AddEdge(vertices[i], vertices[i + 1]);
            }
            
            var visitCount = 0;
            Action<Vertex<string>> countingAction = vertex => visitCount++;

